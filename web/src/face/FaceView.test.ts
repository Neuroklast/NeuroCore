import { createElement } from "react";
import { expect, it } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";
import { FaceView } from "./FaceView";
it("shows meaningful meters without invented thermal readings or data rain",()=>{
 const html=renderToStaticMarkup(createElement(FaceView));
 expect(html).not.toContain('CORE_TEMP');
 expect(html).not.toContain('AST_CHECKSUM');
 expect(html).not.toContain('TEMP (K)');
 expect(html).not.toContain('nk-face-rain-col');
  expect(html).toContain('INPUT PEAK');
  expect(html).toContain('OUTPUT PEAK');
   expect(html).toContain('nk-face-hud');
   expect(html).toContain('nk-face-k');
   expect(html).toContain('nk-face-n');
   expect(html).toContain('nk-face-u');
   expect(html).toContain('kHz');
   expect(html).not.toContain('44.1 kHz');
 expect(html).toContain('DYNAMICS');
 expect(html).toContain('SPECTRUM');
  expect(html).toContain('PARTICLE ORBITS');
  expect(html).toContain('LOW');
  expect(html).toContain('BAND ENERGY');
  expect(html).toContain('SIGNAL FIELD');
  expect(html).toContain('STEREO FIELD');
  expect(html).toContain('PEAK');
  expect(html).toContain('CREST');
  expect(html).toContain('>LOW<');
  expect(html).toContain('>HIGH<');
  expect(html).toContain('IDLE');
  expect((html.match(/data-on="0"/g) ?? []).length).toBeGreaterThanOrEqual(24);
});
